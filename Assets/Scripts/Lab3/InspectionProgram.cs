        };

        public static IReadOnlyList<WizardStep> Steps { get; } = Array.AsReadOnly(StepsInternal);

        public static int QuestionCount
        {
            get
            {
                int count = 0;
                foreach (WizardStep step in StepsInternal)
                {
                    if (step.IsQuestion)
                    {
                        count++;
                    }
                }

                return count;
            }
        }
