    /// </summary>
    public static class InspectionProgram
    {
        /// <summary>Мінімальна частка правильних відповідей для допуску до огляду.</summary>
        public const float PassRatio = 0.6f;

        private static readonly WizardStep[] StepsInternal =
        {
            WizardStep.Instruction(
